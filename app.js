const toast = document.querySelector("[data-toast]");
let lastFocusedElement = null;

function onScroll() {
  const scrollable = document.documentElement.scrollHeight - window.innerHeight;
  const percentage = scrollable > 0 ? (window.scrollY / scrollable) * 100 : 0;
  progress.style.width = `${percentage}%`;

}

function renderProject(project) {
  dialog.querySelector("[data-dialog-index]").textContent = project.index;
  dialog.querySelector("[data-dialog-title]").textContent = project.title;
  dialog.querySelector("[data-dialog-deck]").textContent = project.deck;
  const visual = dialog.querySelector("[data-dialog-visual]");
  visual.className = `dialog-visual ${project.visual}`;
  visual.innerHTML = project.image ? `<img src="${project.image}" alt="${project.imageAlt}">` : "";
  visual.setAttribute("aria-hidden", String(!project.image));
  dialog.querySelector("[data-dialog-meta]").innerHTML = project.meta
    .map(([label, value]) => `<div><span>${label}</span><strong>${value}</strong></div>`)
    .join("");
  dialog.querySelector("[data-dialog-body]").innerHTML = project.body;
}

projectButtons.forEach((button) => {
  button.addEventListener("click", () => {
    const project = projects[button.dataset.project];
    if (!project) return;
    lastFocusedElement = button;
    renderProject(project);
    dialog.showModal();
    document.body.classList.add("dialog-open");
    closeDialogButton.focus();
  });
});

function closeProject() {
  dialog.close();
  document.body.classList.remove("dialog-open");
  lastFocusedElement?.focus();
}

closeDialogButton.addEventListener("click", closeProject);

dialog.addEventListener("click", (event) => {
  if (event.target === dialog) closeProject();
});

dialog.addEventListener("close", () => {
  document.body.classList.remove("dialog-open");
  dialog.querySelector("[data-dialog-body]").replaceChildren();
});

dialog.addEventListener("click", (event) => {
  const selected = event.target.closest("[data-episode]");
  if (!selected || !dialog.contains(selected)) return;
  const id = selected.dataset.videoId;
  const episode = Number(selected.dataset.episode);
  if (!/^[A-Za-z0-9_-]{11}$/.test(id) || !Number.isInteger(episode)) return;
  const player = dialog.querySelector("[data-episode-player]");
  if (!player || selected.getAttribute("aria-pressed") === "true") return;
  player.src = `https://www.youtube-nocookie.com/embed/${id}`;
  player.title = `Real Parenting Course facilitator guide — Episode ${episode}`;
  dialog.querySelector("[data-episode-current]").textContent = `Episode ${episode} / Facilitator Guide`;
  dialog.querySelector("[data-episode-link]").href = `https://www.youtube.com/watch?v=${id}`;
  dialog.querySelectorAll("[data-episode]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button === selected));
  });
});

